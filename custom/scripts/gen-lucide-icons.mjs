// Build src/editor/lucide-icons.generated.js from lucide-icon-map.json:
// a {haxIconName: dataUrl} map holding only the Lucide SVGs we use.
//   node scripts/gen-lucide-icons.mjs   (runs automatically before `npm run build`)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.resolve(here, "..");
const require = createRequire(import.meta.url);
const lucideDir = path.join(path.dirname(require.resolve("lucide-static/package.json")), "icons");
const { version } = require("lucide-static/package.json");

const map = JSON.parse(readFileSync(path.join(root, "src/editor/lucide-icon-map.json"), "utf8"));

const missing = [];
const cache = {};
const out = {};
for (const [haxName, lucideName] of Object.entries(map)) {
  if (!(lucideName in cache)) {
    try {
      cache[lucideName] = readFileSync(path.join(lucideDir, `${lucideName}.svg`), "utf8")
        .replace(/<!--[\s\S]*?-->/g, "")
        .replace(/\s*\n\s*/g, " ")
        .replace(/class="[^"]*"/, "")
        .trim();
    } catch {
      missing.push(`${haxName} -> ${lucideName}`);
      continue;
    }
  }
  out[haxName] = `data:image/svg+xml,${encodeURIComponent(cache[lucideName])}`;
}

if (missing.length) {
  console.error(`Unknown Lucide icons:\n  ${missing.join("\n  ")}`);
  process.exit(1);
}

writeFileSync(
  path.join(root, "src/editor/lucide-icons.generated.js"),
  `// Generated by scripts/gen-lucide-icons.mjs from lucide-icon-map.json.
// Lucide v${version}, ISC license (https://lucide.dev). Do not edit by hand.
export const LUCIDE_ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};
`,
);
console.log(`wrote ${Object.keys(out).length} icons (${Object.keys(cache).length} unique Lucide SVGs)`);
